export function getServicePage(slug: string): ServicePage | undefined {
  return servicePages.find((page) => page.slug === slug);
}

/** Направление формы для slug базовой или отдельной страницы услуги. */
export function formServiceFor(slug: string | undefined): BaseServiceSlug | "" {
  if (!slug) return "";
  if (slug === "ocenka" || slug === "sudebnaya-ekspertiza" || slug === "ekspertnye-issledovaniya") return slug;
  return getServicePage(slug)?.formService ?? "";
}

/** Отдельные страницы, связанные с базовым направлением (для перелинковки). */
export function servicePagesFor(base: BaseServiceSlug): ServicePage[] {
  return servicePages.filter(
    (page) => page.parent === base || (page.parent === null && page.formService === base) || page.related.includes(base),
  );
}
